import {createRequire} from 'node:module'
import assert from 'node:assert/strict'
const require=createRequire(import.meta.url)
const {chromium}=require(process.env.PLAYWRIGHT_PACKAGE)
const browser=await chromium.launch({headless:true})
const page=await browser.newPage({viewport:{width:1440,height:1000}})
const errors=[]
page.on('pageerror',e=>errors.push(e.message))
page.on('response',r=>{if(r.status()>=400&&r.url().includes('/usunknown/'))errors.push(r.status()+' '+r.url())})
await page.goto('http://127.0.0.1:5178/Portafolio/')
await page.getByRole('button',{name:'Jugar en el navegador'}).click()
await page.getByRole('button',{name:'Entrar en la mansión'}).waitFor()
assert.equal(Math.round((await page.getByRole('dialog').boundingBox()).width),1440)
await page.screenshot({path:'test-results/usunknown-menu.png'})
await page.getByRole('button',{name:'Entrar en la mansión'}).click()
await page.waitForTimeout(1600)
await page.screenshot({path:'test-results/usunknown-intro.png'})
await page.waitForTimeout(9000)
await page.getByText('Llaves 0 / 4').waitFor()
await page.screenshot({path:'test-results/usunknown-playing.png'})
await page.keyboard.down('KeyA')
await page.waitForTimeout(1000)
await page.keyboard.up('KeyA')
await page.evaluate(()=>window.dispatchEvent(new Event('blur')))
await page.getByRole('heading',{name:'Un respiro.'}).waitFor()
await page.getByRole('button',{name:'Continuar',exact:true}).last().click()
await page.keyboard.press('KeyF')
await page.getByText('Luz OFF',{exact:false}).waitFor()
await page.keyboard.press('Escape')
await page.getByRole('heading',{name:'Un respiro.'}).waitFor()
await page.getByRole('button',{name:'Continuar',exact:true}).last().click()
await page.keyboard.press('KeyR')
await page.getByText('Luz ON',{exact:false}).waitFor()
await page.getByRole('button',{name:'Táctil',exact:true}).click()
await page.getByRole('button',{name:'Usar',exact:true}).click()
await page.getByRole('button',{name:'Cerrar juego'}).click()
await page.getByRole('dialog').waitFor({state:'detached'})
assert.equal(await page.evaluate(()=>document.body.style.overflow),'')
await page.getByRole('button',{name:'Jugar en el navegador'}).click()
await page.getByRole('button',{name:'Entrar en la mansión'}).click()
await page.keyboard.press('Space')
await page.getByText('Llaves 0 / 4').waitFor()
await page.setViewportSize({width:390,height:844})
await page.getByRole('button',{name:'Táctil',exact:true}).click()
await page.screenshot({path:'test-results/usunknown-mobile.png'})
assert.deepEqual(errors,[])
console.log('PASS: desktop, intro completion and skip, audio resources, flashlight, pause, restart, touch UI, close/reopen and mobile layout')
await browser.close()
